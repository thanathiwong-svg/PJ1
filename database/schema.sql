);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_customer_updated_at
BEFORE UPDATE ON customer
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_wallet_updated_at
BEFORE UPDATE ON wallet
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_computer_updated_at
BEFORE UPDATE ON computer
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_ticket_updated_at
BEFORE UPDATE ON support_ticket
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ============================================================
-- SQL Function: calc_rental_price
-- ระบบเช่าคอมออนไลน์ SunFlowerPC (PostgreSQL / Supabase)
-- หน้าที่: คำนวณราคาเช่า = ราคาต่อชั่วโมงของเครื่อง x จำนวนชั่วโมง
-- ============================================================

CREATE OR REPLACE FUNCTION calc_rental_price(p_computer_id INTEGER, p_hours NUMERIC)
RETURNS NUMERIC(10,2)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
  v_price_per_hour NUMERIC(10,2);
BEGIN
  IF p_hours IS NULL OR p_hours <= 0 THEN
    RAISE EXCEPTION 'จำนวนชั่วโมงต้องมากกว่า 0';
  END IF;

  SELECT price_per_hour INTO v_price_per_hour
  FROM computer
  WHERE computer_id = p_computer_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'ไม่พบเครื่องรหัส %', p_computer_id;
  END IF;

  RETURN ROUND(v_price_per_hour * p_hours, 2);
END;
$$;

