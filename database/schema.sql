  comment VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_rating_rental
    FOREIGN KEY (rental_id) REFERENCES rental(rental_id),
  CONSTRAINT fk_rating_customer
