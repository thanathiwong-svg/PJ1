-- ============================================================
-- Stored Procedure: sp_end_rental
-- ระบบเช่าคอมออนไลน์ SunFlowerPC (PostgreSQL 11+ / Supabase)
-- หน้าที่: จบรายการเช่า (ปิดเครื่อง) และคืนสถานะเครื่องให้ว่าง
-- เรียกใช้: CALL sp_end_rental(rental_id, customer_id);
-- ============================================================

CREATE OR REPLACE PROCEDURE sp_end_rental(p_rental_id INTEGER, p_customer_id INTEGER)
LANGUAGE plpgsql
AS $$
DECLARE
  v_rental rental%ROWTYPE;
BEGIN
  SELECT * INTO v_rental
  FROM rental
  WHERE rental_id = p_rental_id AND customer_id = p_customer_id
  FOR UPDATE;

  IF NOT FOUND OR v_rental.status <> 'active' THEN
    RAISE EXCEPTION 'รายการนี้ไม่ได้กำลังใช้งานอยู่';
  END IF;

  UPDATE session
  SET status = 'ended', ended_at = CURRENT_TIMESTAMP,
      remaining_seconds = 0, connection_enabled = FALSE
  WHERE rental_id = p_rental_id AND status = 'active';

  UPDATE rental
  SET status = 'completed', remaining_minutes = 0, end_time = CURRENT_TIMESTAMP
  WHERE rental_id = p_rental_id;

  UPDATE reservation
  SET status = 'completed', end_time = CURRENT_TIMESTAMP
  WHERE reservation_id = v_rental.reservation_id;

  UPDATE computer c
  SET status = 'available'
  WHERE c.computer_id = v_rental.computer_id
    AND c.status <> 'maintenance'
    AND NOT EXISTS (
      SELECT 1 FROM rental r
      WHERE r.computer_id = c.computer_id
        AND r.status = 'active'
        AND r.rental_id <> p_rental_id
    );
END;
$$;

